"""Assets for the warden and Darkness, from 1.19.2.

    python -I tools/warden/generate.py

Entity textures, the sonic boom particle's sprites, the Darkness icon, the warden's sounds (and the parrot's
imitation), English names, subtitles and death messages, and the warden's animations: 1.19.2's keyframe data
converted to this mod's small animation classes (warden/client/WardenAnimations.java).

The warden's four replies to a shriek belong to the sculk stream's sounds (its shrieker plays them with or without
the warden): `listening_angry` is written here only while tools/sculk/.sounds does not list it.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import assets  # noqa: E402

M = assets.MODID
SRC = "G:/MCDownloads/wu-1.19.2-src/net/minecraft/client/animation/definitions/WardenAnimation.java"

for t in ("warden", "warden_bioluminescent_layer", "warden_heart", "warden_pulsating_spots_1", "warden_pulsating_spots_2"):
    assets.texture("entity/warden/" + t)
for i in range(16):
    assets.texture("particle/sonic_boom_%d" % i)
assets.texture("mob_effect/darkness")

SCULK_OWNS = {"entity.warden.nearby_close", "entity.warden.nearby_closer", "entity.warden.nearby_closest"}
sculk_marker = os.path.join(assets.ROOT, "tools", "sculk", ".sounds")
if os.path.exists(sculk_marker):
    SCULK_OWNS |= set(open(sculk_marker, encoding="utf-8").read().split())

events = {}
for e in ("agitated", "ambient", "angry", "attack_impact", "death", "dig", "emerge", "heartbeat", "hurt", "listening",
          "listening_angry", "roar", "sniff", "sonic_boom", "sonic_charge", "step", "tendril_clicks"):
    name = "entity.warden." + e
    if name not in SCULK_OWNS:
        events[name] = assets.copy_sound(name)
parrot = assets.copy_sound("entity.parrot.imitate.warden")
for s in parrot["sounds"]:
    if isinstance(s, dict) and s.get("type") == "event":
        s["name"] = "%s:%s" % (M, s["name"])
events["entity.parrot.imitate.warden"] = parrot
assets.merge_sounds("warden", events)

lines = [
    "entity.%s.warden.name=%s" % (M, assets.name("entity.minecraft.warden")),
    "effect.%s.darkness=%s" % (M, assets.name("effect.minecraft.darkness")),
    "death.attack.sonic_boom=%s" % assets.name("death.attack.sonic_boom"),
    "death.attack.sonic_boom.player=%s" % assets.name("death.attack.sonic_boom.player"),
    "death.attack.sonic_boom.item=%s" % assets.name("death.attack.sonic_boom.item"),
]
lines += assets.subtitle_lines(events)
assets.merge_lang("warden", lines)

# --- animations ---------------------------------------------------------------------------------------------------
src = open(SRC, encoding="utf-8").read()
body = src[src.index("public class WardenAnimation {") + len("public class WardenAnimation {"):src.rindex("}")]
body = body.replace("AnimationChannel.Targets.", "Targets.").replace("AnimationChannel.Interpolations.", "Interpolations.")
body = body.replace("KeyframeAnimations.", "")
body = body.replace("AnimationDefinition.Builder.withLength", "AnimationDefinition.withLength")
body = re.sub(r"\n   ", "\n    ", body)
java = '''package com.exiledradio.wildupdatebackport.warden.client;

import com.exiledradio.wildupdatebackport.warden.client.anim.AnimationChannel;
import com.exiledradio.wildupdatebackport.warden.client.anim.AnimationChannel.Interpolations;
import com.exiledradio.wildupdatebackport.warden.client.anim.AnimationChannel.Targets;
import com.exiledradio.wildupdatebackport.warden.client.anim.AnimationDefinition;
import com.exiledradio.wildupdatebackport.warden.client.anim.Keyframe;

import static com.exiledradio.wildupdatebackport.warden.client.anim.KeyframeAnimations.degreeVec;
import static com.exiledradio.wildupdatebackport.warden.client.anim.KeyframeAnimations.posVec;

/**
 * The warden's six animations: 1.19.2's keyframes, unchanged. Generated by {@code tools/warden/generate.py}; do not edit.
 */
public final class WardenAnimations {

    private WardenAnimations() {
    }
''' + body.rstrip() + "\n}\n"
out = os.path.join(assets.ROOT, "src", "main", "java", "com", "exiledradio", M, "warden", "client", "WardenAnimations.java")
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write(java)
print("warden: %d sound events, %d lang lines, animations" % (len(events), len(lines)))
